// Acceptance tests 5–7 and 10 (clean scope): independent theme outputs,
// deterministic packages, scoped clean.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { tempDir, run, treeHashes, cloneTheme } from './helpers.mjs';
import { isSharedClass } from '../../packages/build/lib/shared-classes.mjs';

test('building DZP leaves Bond\'s published output byte-for-byte unchanged', () => {
  const P = tempDir();
  assert.equal(run(['build', 'bond'], { BOND_PUBLISH_ROOT: P }).code, 0);
  const before = treeHashes(path.join(P, 'bond'));
  const mtimes = fs.statSync(path.join(P, 'bond', 'packages', 'DNN.Themes.Bond_01.01.00_Install.zip')).mtimeMs;
  const r = run(['build', 'dzp'], { BOND_PUBLISH_ROOT: P });
  assert.equal(r.code, 0, r.out);
  assert.deepEqual(treeHashes(path.join(P, 'bond')), before);
  assert.equal(fs.statSync(path.join(P, 'bond', 'packages', 'DNN.Themes.Bond_01.01.00_Install.zip')).mtimeMs, mtimes, 'Bond ZIP not rewritten');
  assert.ok(fs.existsSync(path.join(P, 'dzp', 'packages', 'DNN.Themes.DZP_01.00.00_Install.zip')));
});

test('production builds are deterministic (same commit + lockfile -> identical artifacts)', () => {
  const A = tempDir(); const B = tempDir();
  assert.equal(run(['build', 'bond'], { BOND_PUBLISH_ROOT: A }).code, 0);
  assert.equal(run(['build', 'bond'], { BOND_PUBLISH_ROOT: B }).code, 0);
  const a = treeHashes(path.join(A, 'bond')); const b = treeHashes(path.join(B, 'bond'));
  // Reports record wall-clock time and duration by design; everything that ships must match.
  for (const k of Object.keys(a)) if (!k.startsWith('reports/')) assert.equal(b[k], a[k], `${k} differs between builds`);
  assert.deepEqual(Object.keys(a).sort(), Object.keys(b).sort());
  const ma = JSON.parse(fs.readFileSync(path.join(A, 'bond', 'reports', 'build-manifest.json'), 'utf8'));
  const mb = JSON.parse(fs.readFileSync(path.join(B, 'bond', 'reports', 'build-manifest.json'), 'utf8'));
  assert.equal(ma.package.sha256, mb.package.sha256);
  assert.deepEqual(ma.outputs, mb.outputs);
});

test('cross-theme isolation: no theme bundle contains another theme\'s classes', () => {
  const P = tempDir();
  assert.equal(run(['build', '--all'], { BOND_PUBLISH_ROOT: P }).code, 0);
  const bond = fs.readFileSync(path.join(P, 'bond', 'theme', 'Skins', 'DNN.Themes.Bond', 'skin.css'), 'utf8');
  const dzp = fs.readFileSync(path.join(P, 'dzp', 'theme', 'Skins', 'DNN.Themes.DZP', 'skin.css'), 'utf8');
  assert.ok(!/\.dzp-/.test(bond));
  // DZP may use shared classes (.bond-button: block defined in packages/) but never the Bond theme's own.
  const bondThemeOnly = [...dzp.matchAll(/\.(bond-[a-z0-9_-]+)/g)].map((m) => m[1]).filter((c) => !isSharedClass(c));
  assert.deepEqual(bondThemeOnly, []);
  // Each theme ships its own copy of the shared components (no runtime dependency on the other).
  assert.ok(bond.includes('.bond-button') && dzp.includes('.bond-button'));
  assert.ok(!fs.readdirSync(path.join(P, 'dzp', 'theme', 'Skins')).includes('DNN.Themes.Bond'));
});

test('shared splash: every theme ships the same, self-contained splash layout', () => {
  const P = tempDir();
  assert.equal(run(['build', '--all'], { BOND_PUBLISH_ROOT: P }).code, 0);
  const skinDir = (id, name) => path.join(P, id, 'theme', 'Skins', name);
  const bond = skinDir('bond', 'DNN.Themes.Bond'); const dzp = skinDir('dzp', 'DNN.Themes.DZP');
  assert.equal(fs.readFileSync(path.join(dzp, 'splash.ascx'), 'utf8'), fs.readFileSync(path.join(bond, 'splash.ascx'), 'utf8'));
  // Same compiled CSS apart from the per-theme banner line: theme tokens never reach it.
  const body = (dir) => fs.readFileSync(path.join(dir, 'splash.css'), 'utf8').replace(/^\/\*![^*]*\*\/\n/, '');
  assert.equal(body(dzp), body(bond));
  assert.ok(!/var\(--bond-(?!splash-)/.test(body(bond)), 'splash.css reads only its own --bond-splash-* values');
  for (const f of ['resources/vendor/splash/assets/img/bond-for-web-solutions-logo.png', 'resources/vendor/splash/assets/font/MuseoSans_500.otf']) {
    assert.ok(fs.existsSync(path.join(dzp, f)), `dzp lacks ${f}`);
  }
  // Self-contained: it includes only the shared control registrations, no theme partials or scripts.
  const ascx = fs.readFileSync(path.join(dzp, 'splash.ascx'), 'utf8');
  assert.deepEqual([...ascx.matchAll(/#include file="([^"]+)"/g)].map((m) => m[1]), ['partials/_registers.ascx']);
  assert.ok(!/DnnJsInclude|DnnCssInclude/.test(ascx));
});

test('clean removes only the requested theme and refuses unknown or traversal ids', () => {
  const P = tempDir();
  assert.equal(run(['build', '--all'], { BOND_PUBLISH_ROOT: P }).code, 0);
  fs.writeFileSync(path.join(P, 'keep-me.txt'), 'not generated by bond');
  assert.equal(run(['clean', 'dzp'], { BOND_PUBLISH_ROOT: P }).code, 0);
  assert.ok(!fs.existsSync(path.join(P, 'dzp')));
  assert.ok(fs.existsSync(path.join(P, 'bond', 'packages')));
  for (const bad of ['../bond', '..', 'C:\\Windows', 'nope']) {
    const r = run(['clean', bad], { BOND_PUBLISH_ROOT: P });
    assert.equal(r.code, 1, `clean ${bad} must fail`);
    assert.match(r.out, /BOND041/);
  }
  assert.equal(run(['clean', '--all'], { BOND_PUBLISH_ROOT: P }).code, 0);
  assert.ok(!fs.existsSync(path.join(P, 'bond')));
  assert.ok(fs.existsSync(path.join(P, 'keep-me.txt')), 'unknown files are left alone');
});

