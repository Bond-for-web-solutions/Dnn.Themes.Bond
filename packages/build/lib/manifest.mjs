// Generates the DNN extension manifest (.dnn). Structure mirrors the verified
// legacy Bond manifest: one Skin package + one Container package, each with a
// ResourceFile component, plus generated Cleanup components for upgrades.
import { xmlEscape as x } from './util.mjs';

const win = (p) => p.replace(/\//g, '\\');

function owner(o = {}) {
  return `      <owner>
        <name>${x(o.name)}</name>
        <organization>${x(o.organization)}</organization>
        <url>${x(o.url)}</url>
        <email>${x(o.email)}</email>
      </owner>`;
}

function cleanup(version, basePath, files) {
  if (!files.length) return '';
  const items = files.map((f) => {
    const i = f.lastIndexOf('/');
    return `            <file>\n              <path>${x(win(i < 0 ? '' : f.slice(0, i)))}</path>\n              <name>${x(i < 0 ? f : f.slice(i + 1))}</name>\n            </file>`;
  }).join('\n');
  return `        <component type="Cleanup" version="${version}">
          <files>
            <basePath>${x(basePath)}</basePath>
${items}
          </files>
        </component>
`;
}

/**
 * @param {object} o
 * @param {object} o.dnn theme.json "dnn" section
 * @param {string} o.version DNN version 01.02.03
 * @param {string[]} o.layouts root-level skin .ascx files
 * @param {string[]} o.containers root-level container .ascx files
 * @param {boolean} o.hasSkinResources
 * @param {boolean} o.hasContainerResources
 * @param {{skin: string[], container: string[]}} o.cleanup files removed since earlier releases
 */
export function generateManifest({ dnn, version, layouts, containers, hasSkinResources, hasContainerResources, cleanup: removed }) {
  const skinBase = `Portals\\_default\\Skins\\${dnn.skinName}`;
  const containerBase = `Portals\\_default\\Containers\\${dnn.containerName}`;
  const deps = `      <dependencies>
        <dependency type="CoreVersion">${x(dnn.coreVersion)}</dependency>
      </dependencies>`;
  const skinFiles = layouts.map((l) => `            <skinFile>\n              <path></path>\n              <name>${x(l)}</name>\n            </skinFile>`).join('\n');
  const resource = (base, name) => `        <component type="ResourceFile">
          <resourceFiles>
            <basePath>${x(base)}</basePath>
            <resourceFile>
              <name>${name}</name>
            </resourceFile>
          </resourceFiles>
        </component>
`;
  let xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by @bond/build from theme.json. Do not edit; see docs/build-system.md. -->
<dotnetnuke type="Package" version="5.0">
  <packages>
    <package name="${x(dnn.packageName)}" type="Skin" version="${version}">
      <friendlyName>${x(dnn.friendlyName)}</friendlyName>
      <description>${x(dnn.description)}</description>
${owner(dnn.owner)}
      <license src="License.txt" />
      <releaseNotes src="ReleaseNotes.txt" />
${deps}
      <components>
${cleanup(version, skinBase, removed.skin)}        <component type="Skin">
          <skinFiles>
            <basePath>${x(skinBase)}</basePath>
            <skinName>${x(dnn.skinName)}</skinName>
${skinFiles}
          </skinFiles>
        </component>
${hasSkinResources ? resource(skinBase, 'Resources.zip') : ''}      </components>
    </package>
`;
  if (containers.length) {
    const containerFiles = containers.map((c) => `            <containerFile>\n              <path></path>\n              <name>${x(c)}</name>\n            </containerFile>`).join('\n');
    xml += `    <package name="${x(dnn.containerPackageName)}" type="Container" version="${version}">
      <friendlyName>${x(dnn.containerFriendlyName || dnn.containerPackageName)}</friendlyName>
      <description>${x(dnn.containerDescription || `Containers for the ${dnn.friendlyName} skin.`)}</description>
${owner(dnn.owner)}
      <license src="License.txt" />
      <releaseNotes src="ReleaseNotes.txt" />
${deps}
      <components>
${cleanup(version, containerBase, removed.container)}        <component type="Container">
          <containerFiles>
            <basePath>${x(containerBase)}</basePath>
            <containerName>${x(dnn.containerName)}</containerName>
${containerFiles}
          </containerFiles>
        </component>
${hasContainerResources ? resource(containerBase, 'ContainerResources.zip') : ''}      </components>
    </package>
`;
  }
  xml += '  </packages>\n</dotnetnuke>\n';
  return xml;
}

/**
 * Light structural check of a manifest (no XML dependency): balanced tags, the
 * expected root, and the files it references. Returns problems as strings.
 */
export function checkManifestXml(xml) {
  const problems = [];
  if (!/^<\?xml[^>]*\?>\s*(<!--[\s\S]*?-->\s*)?<dotnetnuke\b[^>]*type="Package"/.test(xml)) problems.push('Root element must be <dotnetnuke type="Package">.');
  const stack = [];
  const body = xml.replace(/<\?[\s\S]*?\?>/g, '').replace(/<!--[\s\S]*?-->/g, '');
  for (const m of body.matchAll(/<(\/?)([A-Za-z][\w.-]*)\b[^>]*?(\/?)>/g)) {
    if (m[3]) continue;
    if (!m[1]) stack.push(m[2]);
    else if (stack.pop() !== m[2]) { problems.push(`Unbalanced </${m[2]}>.`); break; }
  }
  if (stack.length) problems.push(`Unclosed <${stack.pop()}>.`);
  if (/&(?!(amp|lt|gt|quot|apos|#\d+|#x[0-9a-f]+);)/i.test(body)) problems.push('Unescaped "&".');
  const referenced = [
    ...[...xml.matchAll(/<(skinFile|containerFile)>\s*<path>([^<]*)<\/path>\s*<name>([^<]+)<\/name>/g)].map((m) => (m[2] ? m[2].replace(/\\/g, '/') + '/' : '') + m[3]),
    ...[...xml.matchAll(/<resourceFile>\s*<name>([^<]+)<\/name>/g)].map((m) => m[1]),
    ...[...xml.matchAll(/<(license|releaseNotes) src="([^"]+)"/g)].map((m) => m[2]),
  ];
  return { problems, referenced: [...new Set(referenced)] };
}
